  function setLang(lang) {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.title = lang === 'zh' ? 'PxeLab - 一体化 PXE 服务器' : 'PxeLab - All-in-one PXE Server';
    const dict = i18n[lang];
    if (!dict) return;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) el.innerHTML = dict[key];
    });
    // Toggle active state
    document.querySelectorAll('#langToggle button').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    localStorage.setItem('pxelab-lang', lang);
  }

  // Init language: localStorage > browser language > default English
  const savedLang = localStorage.getItem('pxelab-lang')
    || (navigator.language.startsWith('zh') ? 'zh' : 'en');
  setLang(savedLang);

  // Bind toggle buttons
  document.querySelectorAll('#langToggle button').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
